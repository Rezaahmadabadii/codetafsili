#!/bin/bash

# ==========================================
# اسکریپت آپدیت کل پوشه به گیت‌هاب
# ==========================================

echo "در حال بررسی و ارسال فایل‌های جدید..."

# ۱. دریافت آخرین تغییرات از گیت‌هاب (برای جلوگیری از تداخل)
git pull origin main

# ۲. اضافه کردن تمام فایل‌های جدید و تغییر یافته
git add .

# ۳. ثبت تغییرات با پیام دلخواه
git commit -m "آپدیت کلی پروژه"

# ۴. ارسال به گیت‌هاب
git push origin main

echo "✅ تمام فایل‌ها با موفقیت در گیت‌هاب آپلود شدند!"